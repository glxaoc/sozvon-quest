const RANK_MIN = [95, 90, 80, 65, 50, 0];
const RANK_LETTER = ['SS', 'S', 'A', 'B', 'C', 'D'];

function get(id) { return TYPES[id] || TYPES.custom; }

function rankFor(total, typeId) {
  const t = get(typeId);
  const i = RANK_MIN.findIndex((m) => total >= m);
  const k = i < 0 ? RANK_MIN.length - 1 : i;
  return { rank: RANK_LETTER[k], title: t.ranks[k] };
}

// Для renderer: без функций
function list() {
  return Object.values(TYPES).map((t) => ({ id: t.id, name: t.name, hint: t.hint, talk: t.talk, templates: t.templates, ranks: t.ranks }));
}

module.exports = { TYPES, get, rankFor, list };
