(async () => {
  let fails = 0;
  const times = [];
  for (const c of cases) {
    const t0 = Date.now();
    const res = await m.check({ theses: c.theses, recentMe: c.recentMe, recentThem: c.recentThem || '' });
    const ms = Date.now() - t0; times.push(ms);
    const got = res.closed.filter((x) => x.confidence >= cfg.CONFIDENCE_THRESHOLD).map((x) => x.id).sort();
    const ok = JSON.stringify(got) === JSON.stringify(c.expect.slice().sort());
    if (!ok) fails++;
    console.log(`${ok ? 'PASS' : 'FAIL'} ${c.name} — ${ms} ms`);
    console.log('  ', res.closed.map((x) => `${x.id}:${x.confidence}`).join(' ') || '—');
  }
  console.log(`model ${cfg.LLM_MODEL}: ${cases.length - fails}/${cases.length}, latency ${Math.min(...times)}–${Math.max(...times)} ms, usage`, m.usage);
  process.exit(fails ? 1 : 0);
})().catch((e) => { console.error('ERROR', e.message); process.exit(2); });
